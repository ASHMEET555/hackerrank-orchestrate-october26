"""Regenerate code/notes/TRACE_CHECKS.md from engine output and raw evidence (tooling; may read the answer key
ONLY to list resources the engine failed to produce for sample cases - never used by engine code)."""
import csv, json, re, sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "code"))
from identity import IdentityResolver
from loaders import ManifestLoader
from state_reconstructor import StateReconstructor
from rules_engine import PolicyEngine
from status_decider import StatusDecider
from intent import classify_intent
from timeutil import parse_iso

DS = root / "dataset"
CASES = ["case_36", "case_37", "case_40", "case_05", "case_11", "case_14", "case_31", "case_32"]
PIPE_STATUS = {"FOUND": "PRESENT", "NOT_FOUND": "ABSENT", "ACTIVE": "ACTIVE", "IDENTIFIABLE": "PRESENT",
               "REDACTED": "REDACTED", "ANONYMIZED": "ANONYMIZED", "DISABLED": "DISABLED", "BLOCKED": "BLOCKED",
               "PRESENT": "PRESENT", "ABSENT": "ABSENT"}

reqs = {}
for f in ("sample_deletion_requests.csv", "deletion_requests.csv"):
    for r in csv.DictReader(open(DS / f, encoding="utf-8")):
        reqs[r["case_id"]] = r
truth = {r["case_id"]: json.loads(r["steps_json"]) for r in csv.DictReader(open(DS / "sample_output.csv", encoding="utf-8"))}

resolver, recon, engine, manifest = IdentityResolver(DS), StateReconstructor(DS), PolicyEngine(), ManifestLoader(DS)
_cache = {}


def lines_of(fid):
    if fid not in _cache:
        p = manifest.get(fid).absolute_path
        _cache[fid] = p.read_text(encoding="utf-8", errors="replace").splitlines() if p.suffix != ".pdf" and p.suffix != ".png" else None
    return _cache[fid]


def check(fid, rid, state):
    """Return (raw_line, verdict)."""
    if not fid:
        return "(no citation)", "NOT CHECKED"
    ls = lines_of(fid)
    if ls is None:
        return "(binary evidence: PDF/PNG, no line check)", "NOT CHECKED"
    hits = [l.strip() for l in ls if re.search(r"(?<![A-Za-z0-9_])" + re.escape(rid) + r"(?![A-Za-z0-9_])", l)]
    if not hits:
        return "NO MATCHING LINE", "FAIL"
    h = hits[0]
    if "|" in h:
        cols = [c.strip() for c in h.lstrip("- ").split("|")]
        raw = next((PIPE_STATUS[c] for c in cols if c in PIPE_STATUS), None)
        if raw is None:
            return h, "NOT CHECKED"
        return h, "PASS" if raw == state else f"FAIL (raw status {raw} != engine {state})"
    if "rows=0" in h or "http_status=404" in h:
        return h, "PASS" if state == "ABSENT" else f"FAIL (raw says absent, engine {state})"
    if state in ("PRESENT", "ACTIVE"):
        return h, "PASS (row exists)"
    return h, "NOT CHECKED (non-pipe line, engine state %s)" % state


out = ["# Trace Checks Against Raw Evidence", "",
       "Generated by `code/tools/gen_trace_checks.py` from engine output. Do not edit by hand.", ""]
case_fail = []
for cid in CASES:
    r = reqs[cid]
    aat = parse_iso(r["audit_at"])
    subj, _ = resolver.resolve(r["email"], aat)
    states = recon.reconstruct_for_case(cid, subj, aat)
    verdicts = engine.evaluate_all(states)
    status, reason = StatusDecider.decide_status(classify_intent(r["request_text"])[0], verdicts, states)
    out += [f"## {cid} (user {subj.user_id}, audit_at {r['audit_at']})", f"- Engine status: `{status}`", f"- Reason: {reason}", "",
            "| Resource | Engine state | Rule | File:locator | Raw line | Result |", "|---|---|---|---|---|---|"]
    bad = False
    seen = set()
    for s, v in zip(states, verdicts):
        seen.add(s.resource_id)
        raw, res = check(s.file_id, s.resource_id, s.state)
        bad |= res.startswith("FAIL")
        out.append(f"| `{s.resource_id}` | {s.state} | {v.rule_id} | {s.file_id}:{s.locator} | `{raw[:110].replace('|', '/')}` | **{res}** |")
    for st in truth.get(cid, []):
        rid = st["resource_id"]
        if rid in seen or st["phase"] != "VERIFICATION" and st["phase"] != "FINDING":
            continue
        seen.add(rid)
        raw, res = check(st["evidence_id"], rid, {"VERIFY_RECORD_ABSENT": "ABSENT"}.get(st["operation"], st["state"]))
        res = "FAIL (engine produced no resource; " + res + ")" if res.startswith(("PASS", "NOT")) else res
        if raw == "NO MATCHING LINE":
            res = "FAIL (engine produced no resource; no matching line in cited file)"
        bad = True
        out.append(f"| `{rid}` | (missing from engine) | - | {st['evidence_id'] or '-'} | `{raw[:110].replace('|', '/')}` | **{res}** |")
    out.append("")
    if bad:
        case_fail.append(cid)
out.insert(3, f"**Cases failing trace verification: {', '.join(case_fail) if case_fail else 'none'}**")
(root / "code/notes/TRACE_CHECKS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("cases failing trace verification:", case_fail)
print("\n".join(l for l in out if l.startswith("| `") and "FAIL" in l))
